"""
Evaluation-oriented wrapper around the LAOD pipeline's LLM-labeling + YOLO-World
detection steps. laod.laod_yolo() only returns a plotted visualization image
(results[0].plot()), discarding the structured boxes/labels/confidences needed
for batch evaluation. This module re-implements the same two-stage pipeline
(shared LLM prompt, shared YOLO-World model) but returns structured detections
instead, without modifying the original laod.py demo entrypoint.
"""

import torch
from transformers import pipeline
from ultralytics import YOLO

_LLM_SYSTEM_PROMPT = (
	"Just Give the list of objects in given picture seperated by comma. "
	"Do not write anything else. Use singular name of the objects."
)
_LLM_USER_PROMPT = "List the objects that you see in given picture."

_llm_pipe = None
_yolo_model = None


def _get_llm_pipe():
	global _llm_pipe
	if _llm_pipe is None:
		_llm_pipe = pipeline(
			"image-text-to-text",
			model="google/gemma-3-4b-it",
			device_map="auto",
			torch_dtype=torch.bfloat16,
		)
	return _llm_pipe


def _get_yolo_model():
	global _yolo_model
	if _yolo_model is None:
		_yolo_model = YOLO("yolov8x-worldv2.pt")
	return _yolo_model


def generate_scene_labels(image):
	"""Runs the Gemma-3 LLM labeling step, returns the raw list of class-name strings."""
	pipe = _get_llm_pipe()
	messages = [
		{"role": "system", "content": [{"type": "text", "text": _LLM_SYSTEM_PROMPT}]},
		{
			"role": "user",
			"content": [
				{"type": "text", "text": _LLM_USER_PROMPT},
				{"type": "image", "url": image},
			],
		},
	]
	output = pipe(text=messages, max_new_tokens=500)
	llm_response = output[0]["generated_text"][-1]["content"].lower()
	llm_labels = llm_response.replace(", ", ",").split(",")
	return [label.strip() for label in llm_labels if label.strip()]


def laod_yolo_structured(image):
	"""
	Runs the full LAOD (LLM label generation -> YOLO-World open-vocab detection)
	pipeline and returns structured detections instead of a plotted image.

	Returns:
		dict with:
			llm_labels (list of str): raw class vocabulary generated by the LLM.
			detections (list of dict): one entry per detected box, each with
				keys 'box' ([x1, y1, x2, y2]), 'label' (str), 'confidence' (float).
	"""
	llm_labels = generate_scene_labels(image)

	if len(llm_labels) == 0:
		return {"llm_labels": [], "detections": []}

	model = _get_yolo_model()
	# ultralytics YOLO-World's set_classes() recomputes CLIP text embeddings on
	# whichever device the CLIP text-encoder submodule currently sits on, but
	# predict() silently moves the *main* model to cuda after the first call.
	# On a second set_classes() call this desyncs the two, causing a
	# "tensors on cuda:0 vs cpu" crash inside clip.model.encode_text. Forcing
	# the model back to CPU before every set_classes() keeps both parts in
	# sync; predict() will move it back to GPU as needed for the forward pass.
	model.to("cpu")
	model.set_classes(llm_labels)
	results = model.predict(image, verbose=False)

	result = results[0]
	detections = []
	if result.boxes is not None:
		for box in result.boxes:
			xyxy = box.xyxy[0].tolist()
			cls_idx = int(box.cls[0].item())
			conf = float(box.conf[0].item())
			label = result.names[cls_idx]
			detections.append({"box": xyxy, "label": label, "confidence": conf})

	return {"llm_labels": llm_labels, "detections": detections}

